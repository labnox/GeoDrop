export const getLang = (): Language => {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('geodrop-lang');
    if (saved && saved in translations) {
      return saved as Language;
    }
  }
  // Default to Dutch (nl)
  return 'nl';
};

export const setStoredLang = (lang: Language) => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('geodrop-lang', lang);
  }
};

export const getTranslations = (lang: Language) => {
  return (key: TranslationKey, replacements?: Record<string, string | number>) => {
    let translation = translations[lang]?.[key] || translations.nl[key] || translations.en[key] || '';
    if (replacements) {
      Object.entries(replacements).forEach(([k, v]) => {
        translation = translation.replace(`{${k}}`, String(v));
      });
    }
    return translation;
  };
};
